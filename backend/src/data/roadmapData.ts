export const getTopicGlobalId = (subjectSlug: string, orderIndex: number): number => {
  switch (subjectSlug.toLowerCase()) {
    case 'java':
      return orderIndex; // 1 to 26
    case 'python':
      return 100 + orderIndex; // 101 to 120
    case 'dsa':
      return 200 + orderIndex; // 201 to 217
    case 'aptitude':
      return 300 + orderIndex; // 301 to 317
    default:
      return orderIndex;
  }
};

